import build_ems_monthly as m


def test_build():
    rows = [
        {"用電年月": "2026/9", "空間編號": "A108", "房間": "A108_研究室", "進駐分類": "材化所", "用電總量": "1,000.5", "電費": "5,000", "空調系統分攤": "300", "假日空調申請": "", "空壓機用電": ""},
        {"用電年月": "2026/9", "空間編號": "3F茶水間", "房間": "3F茶水間", "進駐分類": "公共", "用電總量": "100", "電費": "500", "空調系統分攤": "", "假日空調申請": "", "空壓機用電": "20"},
        {"用電年月": "2026/10", "空間編號": "A122-1", "房間": "A122-1_實驗室", "進駐分類": "材化所", "用電總量": "50", "電費": "250", "空調系統分攤": "", "假日空調申請": "8", "空壓機用電": ""},
        {"用電年月": "", "空間編號": "", "房間": "合計", "進駐分類": "", "用電總量": "9999"},
    ]
    out = m.build(rows, {"A108", "A122"})
    assert out["months"] == ["2026/9", "2026/10"]
    assert out["park"]["kwh"] == [1100, 50]
    assert out["park"]["public"] == [100, 0]
    assert out["park"]["holiday_ac"] == [0, 8]
    assert out["rooms"] == {"A108": [1000.5, 0.0], "A122": [0.0, 50.0]}
